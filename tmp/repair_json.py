import os

def fix_file(path, marker, diag_data):
    try:
        with open(path, 'r', encoding='utf-8-sig', errors='ignore') as f:
            content = f.read()
        
        idx = content.find(marker)
        if idx == -1:
            print(f"Marker not found in {path}")
            return False
            
        # Find newline after marker line
        newline_idx = content.find('\n', idx)
        if newline_idx == -1: newline_idx = idx + len(marker)
        
        valid_head = content[:newline_idx].rstrip()
        if not valid_head.endswith(','): valid_head += ','
        
        final_content = valid_head + '\n' + diag_data
        
        with open(path, 'w', encoding='utf-8') as f:
            f.write(final_content)
        print(f"Successfully fixed {path}")
        return True
    except Exception as e:
        print(f"Error fixing {path}: {e}")
        return False

