// Commit grouping and the COMMITS.md renderer. Pure: no git, no files (git.mjs reads the log).
//
// BMM's commit subjects are long prose (« Library selection: Enable/Disable keep selection
// mode open … »), not Conventional Commits, so the group comes from keywords. A Conventional
// prefix (feat:, fix(x):, docs:, ci:, chore:, …) still wins when present. Order of the rules
// below is the tie-breaker: a subject that says « CI: … fix … » is CI, a « security fix » is
// security. Only names are ever rendered, never e-mail addresses.

export const GROUPS = [
  { id: 'security', en: 'Security', fr: 'Sécurité' },
  { id: 'features', en: 'Features', fr: 'Nouveautés' },
  { id: 'fixes', en: 'Fixes', fr: 'Corrections' },
  { id: 'docs', en: 'Documentation', fr: 'Documentation' },
  { id: 'ci', en: 'CI and release', fr: 'CI et publication' },
  { id: 'chore', en: 'Chore, dependencies and tidy-up', fr: 'Maintenance, dépendances et rangement' },
  { id: 'other', en: 'Other changes', fr: 'Autres changements' },
];

const CONVENTIONAL = {
  feat: 'features', feature: 'features', fix: 'fixes', bugfix: 'fixes', hotfix: 'fixes', docs: 'docs', doc: 'docs',
  ci: 'ci', build: 'ci', release: 'ci', chore: 'chore', deps: 'chore', refactor: 'chore', style: 'chore',
  test: 'chore', tests: 'chore', perf: 'features', security: 'security', sec: 'security', revert: 'other',
};

const RULES = [
  ['security', /\b(security|securit[ée]|cve-\d|rustsec|ghsa-|xss|csrf|vulnerab|exploit|pentest|hardening|sanitiz)/i],
  ['ci', /(^|\W)(ci|cd)(\W|$)|\bworkflows?\b|github actions|\bgitleaks\b|\bsemgrep\b|\brelease (script|workflow|tool)\b|\bpipeline\b/i],
  ['docs', /^(docs?|readme|changelog)\b|\b(readme|documentation|docs? (site|page|pages)|bmm docs|in-app docs|user guide|tutorial text|changelog)\b/i],
  ['fixes', /\b(fix(e[sd])?|bug|crash(es|ed)?|broken|regression|no longer|repair(ed)?|corrig|wrong|instead of|did not|didn't|was not|failed)\b/i],
  ['features', /\b(add(s|ed)?|new|introduc\w*|support(s|ed)?|implement\w*|features?|nouveau|ajout|first|improv\w*|rework\w*|restyl\w*|redesign\w*)\b/i],
  ['chore', /\b(bump|dependenc\w*|deps|npm audit|pointer|tidy|refactor\w*|clean(ed)?[- ]?up|rename\w*|regenerat\w*|lockfile|cargo update|chore|format(ting)?)\b/i],
];

/** Advisory ids and attack names: a security change whatever else the subject says. */
const ADVISORY = /\b(cve-\d|rustsec-|ghsa-|xss|csrf|vulnerab\w*|pentest)/i;
const rule = (id) => RULES.find((r) => r[0] === id)[1];
/** The topic part of a prose subject starts it (« Library selection: … », « In-app docs: … »). */
const LEAD_ORDER = ['security', 'ci', 'docs', 'fixes', 'features', 'chore'];
/** In the rest, docs and CI words are often incidental (« … BMM Docs pointer »): they come last. */
const FULL_ORDER = ['security', 'fixes', 'features', 'ci', 'docs', 'chore'];

/** Group id for one commit subject. */
export function classifyCommit(subject) {
  const s = String(subject ?? '').trim();
  if (ADVISORY.test(s)) return 'security';
  const conv = /^(\w+)(\([^)]*\))?!?:\s/.exec(s);
  if (conv && CONVENTIONAL[conv[1].toLowerCase()]) return CONVENTIONAL[conv[1].toLowerCase()];
  const lead = s.split(/[:;]/)[0];
  for (const id of LEAD_ORDER) if (rule(id).test(lead)) return id;
  for (const id of FULL_ORDER) if (rule(id).test(s)) return id;
  return 'other';
}

/** { features: [...], fixes: [...], … } in GROUPS order, empty groups omitted. */
export function groupCommits(commits) {
  const by = new Map(GROUPS.map((g) => [g.id, []]));
  for (const cm of commits) by.get(classifyCommit(cm.subject)).push(cm);
  return GROUPS.filter((g) => by.get(g.id).length).map((g) => ({ ...g, commits: by.get(g.id) }));
}

const SUBJECT_MAX = 220;
/** Markdown-safe one-line subject (pipes and angle brackets escaped, long prose trimmed). */
export function cleanSubject(s) {
  let t = String(s ?? '').replace(/\s+/g, ' ').trim().replace(/[<>]/g, (ch) => (ch === '<' ? '&lt;' : '&gt;'));
  if (t.length > SUBJECT_MAX) t = t.slice(0, SUBJECT_MAX - 1).replace(/\s+\S*$/, '') + ' …';
  return t;
}

const day = (iso) => String(iso ?? '').slice(0, 10);

function commitLine(cm, repoUrl) {
  const hash = repoUrl ? `[\`${cm.short}\`](${repoUrl}/commit/${cm.hash})` : `\`${cm.short}\``;
  return `- ${hash} ${day(cm.date)} ${cleanSubject(cm.subject)}${cm.author ? ` *(${cm.author})*` : ''}`;
}

/**
 * COMMITS.md. `main` = { from, to, fromLabel, commits, repoUrl }; `subs` = [{ name, from, to,
 * commits, note, repoUrl }]. English body with a French heading and group names alongside.
 */
export function renderCommitsMd({ version, previous, main, subs = [], generatedAt = new Date().toISOString() }) {
  const out = [];
  out.push(`# Commits in ${version} / Commits de la ${version}`, '');
  out.push(`Generated by \`tools/release\` on ${day(generatedAt)} from \`git log ${main.from.slice(0, 10)}..${main.to.slice(0, 10)}\`` +
    (previous ? ` (previous version: ${previous}, ${main.fromLabel})` : ` (${main.fromLabel})`) + '.');
  out.push('Généré par `tools/release` à partir de l\'historique git. Le journal rédigé à la main reste `Update/changelog_v' + version + '_{EN,FR}.md`.', '');
  out.push(`**${main.commits.length}** commits in BetterModsManager` + subs.map((s) => `, **${s.commits.length}** in ${s.name}`).join('') + '.', '');
  const groups = groupCommits(main.commits);
  out.push('## Summary / Résumé', '', '| Group / Groupe | Commits |', '|---|---:|');
  for (const g of groups) out.push(`| ${g.en} / ${g.fr} | ${g.commits.length} |`);
  out.push('');
  for (const g of groups) {
    out.push(`## ${g.en} / ${g.fr}`, '');
    for (const cm of g.commits) out.push(commitLine(cm, main.repoUrl));
    out.push('');
  }
  if (subs.length) {
    out.push('## Sibling repositories / Dépôts liés', '');
    out.push('Each one is a gitlink in this tree; its log runs between the commit recorded at the previous version and the one recorded now.', '');
    for (const s of subs) {
      out.push(`### ${s.name}`, '');
      if (s.note) out.push(`*${s.note}*`, '');
      if (s.from && s.to) out.push(`\`${s.from.slice(0, 10)}..${s.to.slice(0, 10)}\``, '');
      if (!s.commits.length) { out.push('No commits in this range.', ''); continue; }
      for (const g of groupCommits(s.commits)) {
        out.push(`**${g.en} / ${g.fr}**`, '');
        for (const cm of g.commits) out.push(commitLine(cm, s.repoUrl));
        out.push('');
      }
    }
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}
