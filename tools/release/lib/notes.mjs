// github-release.md (pure): the owner's pattern from Release/1.0.2/github-release.md, i.e. a
// MAINTAINER NOTES comment to delete before pasting, then the public body (the curated
// changelog), the downloads table, the checksums table and the links. Plus the
// `gh release create` command line the tool prints and never runs.

import { sumsTable } from './checksums.mjs';

export const GENERATED_MARK = '<!-- generated by tools/release: re-running the notes step rewrites this file -->';

/** What each published asset is (the downloads table). Unknown names get a neutral line. */
export const ASSET_INFO = {
  'BMM-Setup.exe': 'BetterInstaller: install, update in place, repair, uninstall (also from the command line)',
  'bmm.bpkg': 'Signed app package used by BetterInstaller updates',
  'update.json': 'Signed update descriptor read by installed copies (lists `BMM-Setup.exe` with its SHA-256)',
  'update-manifest.json': "BMM's signed update manifest",
  'lang-en.json': 'English interface strings (Quick Update)',
  'lang-fr.json': 'French interface strings (Quick Update)',
  'lang-template.json': 'Template for community translations (Quick Update)',
  'links.json': 'Links the app reads (Quick Update)',
};

/** The public assets of a release, in publish order: the installer first, then the rest by name. */
export function orderAssets(names) {
  const first = ['BMM-Setup.exe', 'bmm.bpkg', 'update.json', 'update-manifest.json'];
  return [...first.filter((n) => names.includes(n)), ...names.filter((n) => !first.includes(n)).sort()];
}

/**
 * Checks a release's public asset list against what 0.9.11 tolerates: one installer, named
 * BMM-Setup.exe (lowercase .exe), no .msi, no .zip. Returns problems (empty = fine).
 */
export function assetProblems(names) {
  const p = [];
  const inst = names.filter((n) => /\.(exe|msi)$/i.test(n));
  if (inst.length !== 1) p.push(`exactly one installer asset expected, got: ${inst.join(', ') || 'none'}`);
  else if (!/^BMM-Setup\.exe$/.test(inst[0])) p.push(`the installer must be named BMM-Setup.exe, got ${inst[0]}`);
  const zips = names.filter((n) => /\.zip$/i.test(n));
  if (zips.length) p.push(`no .zip on a BMM release (0.9.11 may run it): ${zips.join(', ')}`);
  return p;
}

/** Strip the curated changelog's own H1 (the release body has its own title). */
export function changelogBody(md) {
  return String(md ?? '').replace(/^﻿/, '').replace(/^# .*\r?\n+/, '').trim();
}

/**
 * opts: { version, previous, commit, branch, assets: [{ name, sha256, size }], changelog (md
 * text or null), expires: { 'update.json': iso, 'update-manifest.json': iso } }
 */
export function renderGithubRelease(o) {
  const names = o.assets.map((a) => a.name);
  const expires = Object.entries(o.expires ?? {}).filter(([, v]) => v).map(([k, v]) => `${k} ${v}`).join(', ');
  const out = [];
  out.push(GENERATED_MARK, '<!--', 'MAINTAINER NOTES: delete this block before pasting into GitHub.', '');
  out.push(`Title:   Better Mods Manager ${o.version}`);
  out.push(`Tag:     v${o.version} on the ${o.branch ?? 'release'} commit you built${o.commit ? ` (${o.commit.slice(0, 8)})` : ''}.`);
  out.push('Order:   publish as Latest, NOT as a pre-release (the stable channel reads /releases/latest).', '');
  out.push(`Assets (all in Release/${o.version}/):`);
  out.push(`         ${names.join(', ')}.`);
  out.push('         Exactly ONE installer executable (BMM-Setup.exe), no .msi, no *_x64-setup.exe, no .zip:');
  out.push('         0.9.11 takes the first .msi, else the first .exe/.zip, and runs it.');
  out.push(`         Release/${o.version}/extras/ (NSIS / MSI) is NOT for the GitHub release.`);
  out.push('Signing: update.json and update-manifest.json expire 7 days after signing' + (expires ? ` (${expires})` : '') + '. If you publish later');
  out.push('         than that, re-sign first (`bpkg resign-manifest`, `node scripts/sign-update-manifest.mjs sign`).');
  out.push(`Verify:  Release/${o.version}/SHA256SUMS.txt; BetterInstaller/target/release/bpkg.exe verify --key BetterInstaller/examples/bmm/keys/public.key Release/${o.version}/bmm.bpkg`);
  out.push(`Social preview: Release/${o.version}/media/bmm-${o.version}-social-1200x630.png (Settings → Social preview).`);
  out.push(`Body image (optional): media/bmm-${o.version}-whats-new-1200x675.png`);
  out.push('-->', '');
  out.push(`# Better Mods Manager ${o.version}`, '');
  if (o.changelog) out.push(changelogBody(o.changelog), '');
  else out.push(`*(Update/changelog_v${o.version}_EN.md is missing: write it, then run the notes step again.)*`, '');
  out.push('## Downloads', '', '| File | What it is |', '|---|---|');
  for (const a of o.assets) out.push(`| \`${a.name}\` | ${ASSET_INFO[a.name] ?? ''} |`);
  out.push('', 'Releases are signed (Ed25519). BetterInstaller verifies the signature before it applies an update', 'and refuses a package that does not match.', '');
  out.push('### Checksums (SHA-256)', '', sumsTable(o.assets.map((a) => ({ path: a.name, sha256: a.sha256 }))), '');
  out.push('## Links', '', '- Documentation: https://bettercommunity.ch/docs', '- Discord: https://discord.gg/CTaaEF9R75',
    '- Feedback & Bug Reports: in the app, **Settings → Feedback & Bug Reports**', '');
  out.push(`**Full changelog:** \`Update/changelog_v${o.version}_EN.md\` (French: \`Update/changelog_v${o.version}_FR.md\`)`, '');
  return out.join('\n');
}

/** The publish command (printed, never run). Paths are relative to the repository root. */
export function ghCommand(version, assetNames, notesFile) {
  const files = assetNames.map((n) => `"Release/${version}/${n}"`).join(' ');
  return `gh release create v${version} ${files} --title "Better Mods Manager ${version}" --latest --notes-file "${notesFile}"`;
}
