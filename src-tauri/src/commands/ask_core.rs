// BM25
// ─────────────────────────────────────────────────────────────────────────────

pub struct Index {
    entries: Vec<Entry>,
    docs: Vec<HashMap<String, f64>>,
    titles: Vec<HashSet<String>>,
    len: Vec<f64>,
    df: HashMap<String, usize>,
    avg: f64,
}

impl Index {
    /// Title words count three times, keywords twice, the text once.
    pub fn build(entries: Vec<Entry>) -> Index {
        let mut docs = Vec::with_capacity(entries.len());
        let mut titles = Vec::with_capacity(entries.len());
        let mut len = Vec::with_capacity(entries.len());
        let mut df: HashMap<String, usize> = HashMap::new();
        for e in &entries {
            let mut tf: HashMap<String, f64> = HashMap::new();
            for (text, w) in [(&e.t, 3.0), (&e.kw, 2.0), (&e.x, 1.0)] {
                for t in terms(text) {
                    *tf.entry(t).or_insert(0.0) += w;
                }
            }
            for t in tf.keys() {
                *df.entry(t.clone()).or_insert(0) += 1;
            }
            len.push(tf.values().sum::<f64>().max(1.0));
            docs.push(tf);
            titles.push(terms(&e.t).into_iter().collect());
        }
        let avg = if len.is_empty() { 1.0 } else { len.iter().sum::<f64>() / len.len() as f64 };
        Index { entries, docs, titles, len, df, avg }
    }

    pub fn entry(&self, i: usize) -> &Entry {
        &self.entries[i]
    }

    /// Okapi BM25 (k1 1.2, b 0.75), plus a small prefix match so « activ » finds « activer », and
    /// a bonus for the share of the question's words that are in the TITLE: « export mod list »
    /// is the command called « Export mod list », not the long page that says « export » ten times.
    pub fn search(&self, q: &str, filter: &dyn Fn(&Entry) -> bool) -> Vec<(usize, f64)> {
        let qt: Vec<String> = {
            let mut v = terms(q);
            v.dedup();
            v
        };
        if qt.is_empty() {
            return Vec::new();
        }
        let n = self.entries.len() as f64;
        let (k1, b) = (1.2, 0.75);
        let mut out = Vec::new();
        for (i, tf) in self.docs.iter().enumerate() {
            if !filter(&self.entries[i]) {
                continue;
            }
            let mut s = 0.0;
            for t in &qt {
                let f = tf.get(t).copied().or_else(|| {
                    if t.chars().count() >= 5 {
                        tf.iter().filter(|(k, _)| k.starts_with(t.as_str())).map(|(_, v)| *v * 0.6).fold(None, |a: Option<f64>, v| Some(a.map_or(v, |a| a.max(v))))
                    } else {
                        None
                    }
                });
                if let Some(f) = f {
                    let df = self.df.get(t).copied().unwrap_or(1) as f64;
                    let idf = ((n - df + 0.5) / (df + 0.5) + 1.0).ln();
                    s += idf * f * (k1 + 1.0) / (f + k1 * (1.0 - b + b * self.len[i] / self.avg));
                }
            }
            if s > 0.0 {
                let cov = qt.iter().filter(|t| self.titles[i].contains(*t)).count() as f64 / qt.len() as f64;
                out.push((i, s * (1.0 + 0.8 * cov)));
            }
        }
        out.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
        out
    }
}

