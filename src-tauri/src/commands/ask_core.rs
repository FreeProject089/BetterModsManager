const STOP: &[&str] = &[
    // EN
    "the", "a", "an", "and", "or", "of", "to", "in", "on", "for", "with", "is", "are", "be", "it", "this", "that", "what", "which", "how", "do",
    "does", "can", "i", "my", "me", "you", "your", "there", "any", "from", "by", "as", "at", "if", "when", "where", "why", "who", "should",
    // FR
    "le", "la", "les", "un", "une", "des", "du", "de", "d", "l", "et", "ou", "a", "au", "aux", "en", "dans", "sur", "pour", "avec", "est",
    "sont", "c", "ce", "cet", "cette", "ces", "quoi", "que", "qui", "quel", "quels", "quelle", "quelles", "comment", "pourquoi", "je", "j",
    "mon", "ma", "mes", "tu", "ton", "ta", "tes", "vous", "votre", "vos", "il", "elle", "on", "se", "s", "y", "ne", "pas", "qu", "est-ce",
    "fait", "faire", "t",
];

/// Folded words, stop-words out, plural `s` stripped from long words (« conflits » = « conflit »).
pub fn terms(s: &str) -> Vec<String> {
    L::words(s)
        .into_iter()
        .flat_map(|w| {
            // « engine.ogg » stays whole AND gives « engine » + « ogg »; « Saved-Games » likewise.
            let mut v = vec![w.clone()];
            if w.contains('.') || w.contains('-') {
                v.extend(w.split(['.', '-']).filter(|p| p.chars().count() >= 2).map(str::to_string));
            }
            v
        })
        .filter(|w| !STOP.contains(&w.as_str()))
        .map(|w| if w.chars().count() > 4 && w.ends_with('s') && !w.ends_with("ss") { w[..w.len() - 1].to_string() } else { w })
        .collect()
}

