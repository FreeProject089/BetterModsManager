//! « Ask Laya » — ask BMM a question in plain words and get back the documentation, the setting,
//! the command, the mods or the FILES that answer it. Offline, and never invented text.
//!
//! Mounted twice, like `ai_core`: by the app (`commands::ask_core`, the Ctrl+K « Ask Laya »
//! dialog, the docs hub and the library search) and by the CLI/MCP binary (`bmm ai-ask`,
//! `bmm_ai_ask`). Only external crates, `ai_core` and `ai_laya` (both mounted in both) are used.
//!
//! ## How an answer is found
//!
//! 1. **Deterministic retrieval first.** A BM25 index over what BMM knows: the bundled BMM Docs
//!    pages cut at their headings, the docs hub articles and the palette's commands (all three in
//!    `ask_index.gen.json`, generated by `scripts/gen-ask-index.mjs`), the Settings cards the app
//!    adds at run time, the user's mods (name, description, tags) and profiles. File questions
//!    (« quel mod modifie engine.ogg ? ») and conflict questions (« quels mods sont en conflit ? »)
//!    are answered from the mods' own file lists — exact, not ranked text.
//! 2. **Laya ranks** — only when the embedded model is installed and the AI master switch
//!    allows it: one `choice` question picks the best of the top candidates (+ « none of
//!    these »), and the retrieval score and Laya's vote are averaged; without Laya, the retrieval
//!    order stands. The intent (documentation / setting / files / conflicts / mods / command) is
//!    routed by keyword rules: a Laya intent question was measured and lost to them (19/36
//!    against 27/36, `ai_eval::measure_ask`), so it is not asked.
//! 3. **Display, never generate.** The result is a list of things that exist — a doc section with
//!    its own text as the snippet, a setting to jump to, a command to run, mods and the files they
//!    provide — each with an action. Nothing is written by a model.

