#[derive(Debug, Clone, Deserialize, Default)]
#[serde(default)]
pub struct Request {
    pub question: String,
    /// "en" | "fr": which language to show a bilingual entry in (both are searched).
    pub lang: String,
    /// "all" | "docs" | "mods".
    pub scope: String,
    pub limit: usize,
    /// Entries only the app knows (its Settings cards), added to the index for this question.
    pub extra: Vec<Entry>,
}

#[derive(Debug, Clone, Serialize)]
pub struct Hit {
    pub kind: String,
    pub id: String,
    pub title: String,
    pub snippet: String,
    /// Final score, 0..1 (retrieval, averaged with Laya's vote when it was asked).
    pub score: f64,
    /// Laya's own probability for this candidate, when asked.
    pub laya: Option<f64>,
    pub action: Value,
}

#[derive(Debug, Clone, Serialize)]
pub struct Answer {
    pub question: String,
    pub intent: String,
    pub intent_p: f64,
    /// How the intent was decided ("rules").
    pub routed_by: String,
    pub hits: Vec<Hit>,
    pub files: Vec<FileHit>,
    pub conflicts: Vec<ConflictHit>,
    /// Laya ranked the candidates (false: retrieval only — AI off, no model, or not needed).
    pub laya: bool,
    /// Laya said none of the candidates answers the question.
    pub low_confidence: bool,
    pub notes: Vec<String>,
    pub ms: u64,
}

fn snippet(x: &str, q: &[String], n: usize) -> String {
    // The sentence that holds the most query words, else the start.
    let sentences: Vec<&str> = x.split_inclusive(['.', '!', '?', ':']).collect();
    let best = sentences
        .iter()
        .enumerate()
        .map(|(i, s)| (i, terms(s).iter().filter(|t| q.contains(t)).count()))
        .max_by(|a, b| a.1.cmp(&b.1).then(b.0.cmp(&a.0)))
        .map(|(i, c)| if c > 0 { i } else { 0 })
        .unwrap_or(0);
    let s: String = sentences[best.min(sentences.len().saturating_sub(1))..].concat();
    let s = s.trim();
    if s.chars().count() <= n { s.to_string() } else { format!("{}…", s.chars().take(n).collect::<String>().trim_end()) }
}

fn mod_entries(lib: &Library) -> Vec<Entry> {
    let mut v: Vec<Entry> = lib
        .mods
        .iter()
        .map(|m| Entry { k: "mod".into(), lang: String::new(), id: format!("mod:{}", m.id), t: m.name.clone(), x: m.description.chars().take(600).collect(), kw: m.tags.join(" "), a: json!({ "mod": m.id, "name": m.name }) })
        .collect();
    v.extend(lib.profiles.iter().map(|p| Entry { k: "profile".into(), lang: String::new(), id: format!("profile:{}", p.id), t: p.name.clone(), x: format!("{} · {} mods", p.game, p.active_count), kw: "profile profil".into(), a: json!({ "profile": p.id }) }));
    v
}

fn kind_fits(intent: &str, k: &str) -> f64 {
    match (intent, k) {
        ("docs", "doc") | ("docs", "article") => 1.0,
        ("setting", "setting") => 1.0,
        ("setting", "doc") | ("setting", "article") => 0.7,
        ("command", "command") => 1.0,
        ("command", "setting") => 0.8,
        ("mods", "mod") | ("mods", "profile") => 1.0,
        ("files", "mod") | ("conflicts", "mod") => 0.8,
        (_, "command") => 0.55,
        (_, "setting") => 0.7,
        (_, "mod") | (_, "profile") => 0.6,
        _ => 0.8,
    }
}

/// Answer a question. `model` is the embedded Laya engine when the caller's gate allows it
/// (`None` = retrieval only, which is always available, offline, with AI off).
#[cfg_attr(not(test), allow(dead_code))]
pub fn answer(req: &Request, lib: &Library, model: Option<&dyn LocalModel>) -> Answer {
    answer_tuned(req, lib, model, &crate::commands::ai_tuning::builtin(crate::commands::ai_tuning::Area::Ask))
}

/// [`answer`] with the user's answer settings for « Ask Laya » (« Réglages des réponses »):
/// `top_k` = how many results Laya compares, the temperature, and when the answer reads as
/// unsure (`low_confidence`): Laya's « none » first, then the threshold and the margin on its
/// best candidate. « Équilibré » is exactly [`answer`] as it was.
pub fn answer_tuned(req: &Request, lib: &Library, model: Option<&dyn LocalModel>, tune: &crate::commands::ai_tuning::Tuning) -> Answer {
    let started = Instant::now();
    let question: String = req.question.trim().chars().take(MAX_QUESTION).collect();
    let limit = if req.limit == 0 { DEFAULT_LIMIT } else { req.limit.min(30) };
    let lang = if req.lang == "fr" { "fr" } else { "en" };
    let scope = req.scope.as_str();
    let mut notes: Vec<String> = Vec::new();
    let qt = terms(&question);

    // Intent: keyword rules. A Laya « what does the user want » question was measured and
    // dropped: it routed 19 of 36 benchmark questions right, the rules 27 (ai_eval::measure_ask).
    let (intents, _decisive) = intent_rules(&question);
    let routed_by = "rules".to_string();
    let mut laya_used = false;
    let (intent, intent_p) = if scope == "mods" { ("mods".to_string(), 1.0) } else { intents[0].clone() };

    // Exact answers.
    let mut files = Vec::new();
    let mut conflicts = Vec::new();
    let mods_named: Vec<String> = {
        // A mod named in the question (« conflits de Better Rifles ? »).
        let fq = L::fold(&question);
        lib.mods.iter().filter(|m| m.name.chars().count() >= 4 && fq.contains(&L::fold(&m.name))).map(|m| m.id.clone()).collect()
    };
    if intent == "files" || !file_terms(&question).is_empty() {
        let mut needles = file_terms(&question);
        if needles.is_empty() {
            // « quel mod modifie les sons du moteur ? » — no file name: search the words in paths.
            needles = qt.iter().filter(|t| t.chars().count() >= 4).cloned().collect();
            files = find_files_words(lib, &needles);
        } else {
            files = find_files(lib, &needles);
        }
    }
    if intent == "conflicts" {
        let only: HashSet<String> = mods_named.iter().cloned().collect();
        conflicts = find_conflicts(lib, &only, 20);
    }

    // Ranked answers.
    let mut entries: Vec<Entry> = Vec::new();
    if scope != "mods" {
        entries.extend(builtin().iter().cloned());
        entries.extend(req.extra.iter().take(400).cloned());
    }
    entries.extend(mod_entries(lib));
    let index = Index::build(entries);
    let filter = |e: &Entry| match scope {
        "mods" => e.k == "mod" || e.k == "profile",
        "docs" => e.k == "doc" || e.k == "article",
        _ => true,
    };
    let raw = index.search(&question, &filter);
    // Collapse the two languages of one entry: keep the best score, show the asked language.
    let mut seen: HashMap<String, usize> = HashMap::new();
    let mut cands: Vec<(usize, f64)> = Vec::new();
    for (i, s) in raw {
        let e = index.entry(i);
        let s = s * kind_fits(&intent, &e.k);
        match seen.get(&e.id) {
            Some(&j) => {
                if cands[j].1 < s {
                    cands[j].1 = s;
                }
                if e.lang == lang {
                    cands[j].0 = i;
                }
            }
            None => {
                seen.insert(e.id.clone(), cands.len());
                cands.push((i, s));
            }
        }
    }
    cands.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
    cands.truncate(40);
    let top = cands.first().map(|c| c.1).unwrap_or(1.0).max(1e-9);
    let mut hits: Vec<Hit> = cands
        .iter()
        .map(|(i, s)| {
            let e = index.entry(*i);
            Hit { kind: e.k.clone(), id: e.id.clone(), title: e.t.clone(), snippet: snippet(&e.x, &qt, 220), score: s / top, laya: None, action: e.a.clone() }
        })
        .collect();

    // Laya picks the best of the top candidates.
    let mut low_confidence = false;
    if let Some(m) = model {
        if hits.len() >= 2 {
            let k = hits.len().min((tune.top_k as usize).clamp(2, 10));
            let mut crit: Vec<(String, String)> = hits[..k]
                .iter()
                .enumerate()
                .map(|(j, h)| (format!("c{}", j), format!("{} — {}", h.title, h.snippet.chars().take(140).collect::<String>())))
                .collect();
            crit.push(("none".into(), "none of these answers the question".into()));
            let q: LayaQuestion = ("best".into(), "choice", "Which of these parts of the mod manager answers the user's question best?".into(), crit);
            match m.predict(&question, &[q]) {
                Ok(resp) => {
                    let lp = crate::commands::ai_tuning::calibrate(&L::choice_probs(&resp, "best"), tune.temperature);
                    let p_none = lp.iter().find(|(c, _)| c == "none").map(|(_, p)| *p).unwrap_or(0.0);
                    for (j, h) in hits.iter_mut().enumerate().take(k) {
                        let p = lp.iter().find(|(c, _)| *c == format!("c{}", j)).map(|(_, p)| *p).unwrap_or(0.0);
                        h.laya = Some(p);
                        let vote = (p * k as f64 / 2.0).min(1.0);
                        h.score = 0.5 * h.score + 0.5 * vote;
                    }
                    for h in hits.iter_mut().skip(k) {
                        h.score *= 0.5;
                    }
                    hits.sort_by(|a, b| b.score.partial_cmp(&a.score).unwrap_or(std::cmp::Ordering::Equal));
                    let mut cand: Vec<f64> = lp.iter().filter(|(c, _)| c != "none").map(|(_, p)| *p).collect();
                    cand.sort_by(|a, b| b.partial_cmp(a).unwrap_or(std::cmp::Ordering::Equal));
                    let best = cand.first().copied().unwrap_or(0.0);
                    let second = cand.get(1).copied().unwrap_or(0.0);
                    low_confidence = p_none >= 0.6 || best < tune.threshold || (tune.margin > 0.0 && cand.len() >= 2 && best - second < tune.margin);
                    laya_used = true;
                }
                Err(e) => notes.push(format!("laya:{}", e.chars().take(80).collect::<String>())),
            }
        }
    }
    hits.truncate(limit);
    for h in hits.iter_mut() {
        h.score = (h.score * 1000.0).round() / 1000.0;
        h.laya = h.laya.map(|p| (p * 1000.0).round() / 1000.0);
    }
    if hits.is_empty() && files.is_empty() && conflicts.is_empty() {
        notes.push("nothing_found".into());
    }
    Answer { question, intent, intent_p: (intent_p * 1000.0).round() / 1000.0, routed_by, hits, files, conflicts, laya: laya_used, low_confidence, notes, ms: started.elapsed().as_millis() as u64 }
}

/// Files whose PATH contains the words (« sons moteur » → Sounds/…/Engines/…). Only for
/// questions without a file name.
fn find_files_words(lib: &Library, words: &[String]) -> Vec<FileHit> {
    if words.is_empty() {
        return Vec::new();
    }
    let mut out = Vec::new();
    for m in &lib.mods {
        let mut hits = Vec::new();
        let mut total = 0;
        for f in &m.files {
            let nf = L::fold(&norm_path(f));
            if words.iter().any(|w| nf.contains(w.as_str())) {
                total += 1;
                if hits.len() < 10 {
                    hits.push(f.replace('\\', "/"));
                }
            }
        }
        if total > 0 {
            out.push(FileHit { mod_id: m.id.clone(), mod_name: m.name.clone(), enabled: m.enabled, files: hits, total });
        }
    }
    out.sort_by(|a, b| b.enabled.cmp(&a.enabled).then(b.total.cmp(&a.total)));
    out.truncate(15);
    out
}

/// Mount the engine a caller may use, after its gate: `Ok(provider)` from the AI gate AND the
/// embedded engine installed. Ask never sends a question anywhere, so only the embedded
/// engine counts.
pub fn usable_model<'a>(settings: &ai_core::AiSettings, killed: bool, m: &'a dyn LocalModel) -> Result<&'a dyn LocalModel, &'static str> {
    if killed {
        return Err("killed");
    }
    if !settings.enabled {
        return Err("ai_off");
    }
    if !settings.ask {
        return Err("feature_off");
    }
    if !m.available() {
        return Err("no_model");
    }
    Ok(m)
}

