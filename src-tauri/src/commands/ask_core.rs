#[derive(Debug, Clone, Serialize)]
pub struct FileHit {
    pub mod_id: String,
    pub mod_name: String,
    pub enabled: bool,
    /// The matching files (at most 10) and how many matched in all.
    pub files: Vec<String>,
    pub total: usize,
}

fn norm_path(p: &str) -> String {
    p.replace('\\', "/").to_lowercase()
}

/// Which mods provide a file matching any of `needles` (a name, a path suffix, a folder).
pub fn find_files(lib: &Library, needles: &[String]) -> Vec<FileHit> {
    let mut out = Vec::new();
    for m in &lib.mods {
        let mut hits: Vec<String> = Vec::new();
        let mut total = 0usize;
        for f in &m.files {
            let nf = norm_path(f);
            let name = nf.rsplit('/').next().unwrap_or(&nf);
            if needles.iter().any(|n| name == n.as_str() || nf.ends_with(&format!("/{}", n)) || nf == *n || (n.contains('/') && nf.contains(n.as_str()))) {
                total += 1;
                if hits.len() < 10 {
                    hits.push(f.replace('\\', "/"));
                }
            }
        }
        if total > 0 {
            out.push(FileHit { mod_id: m.id.clone(), mod_name: m.name.clone(), enabled: m.enabled, files: hits, total });
        }
    }
    out.sort_by(|a, b| b.enabled.cmp(&a.enabled).then(b.total.cmp(&a.total)).then(a.mod_name.cmp(&b.mod_name)));
    out
}

#[derive(Debug, Clone, Serialize)]
pub struct ConflictHit {
    pub a_id: String,
    pub a_name: String,
    pub b_id: String,
    pub b_name: String,
    pub both_enabled: bool,
    pub count: usize,
    pub sample: Vec<String>,
}

/// Pairs of mods that provide the same file (case-insensitive path), both-enabled pairs first.
/// `only` restricts to pairs involving these mod ids.
pub fn find_conflicts(lib: &Library, only: &HashSet<String>, limit: usize) -> Vec<ConflictHit> {
    let mut by_file: HashMap<String, Vec<usize>> = HashMap::new();
    for (i, m) in lib.mods.iter().enumerate() {
        let mut seen: HashSet<String> = HashSet::new();
        for f in &m.files {
            let nf = norm_path(f);
            if seen.insert(nf.clone()) {
                by_file.entry(nf).or_default().push(i);
            }
        }
    }
    let mut pairs: HashMap<(usize, usize), (usize, Vec<String>)> = HashMap::new();
    for (f, ms) in by_file {
        if ms.len() < 2 || ms.len() > 16 {
            // A file every mod ships (a readme) says nothing about a conflict between two.
            continue;
        }
        for x in 0..ms.len() {
            for y in (x + 1)..ms.len() {
                let e = pairs.entry((ms[x], ms[y])).or_insert((0, Vec::new()));
                e.0 += 1;
                if e.1.len() < 5 {
                    e.1.push(f.clone());
                }
            }
        }
    }
    let ignore = |f: &str| {
        let n = f.rsplit('/').next().unwrap_or(f);
        n.starts_with("readme") || n.starts_with("license") || n.starts_with("changelog") || n == "entry.lua" || n == "description.lua" || n.ends_with(".txt") || n.ends_with(".md")
    };
    let mut out: Vec<ConflictHit> = pairs
        .into_iter()
        .filter_map(|((a, b), (count, mut sample))| {
            sample.retain(|f| !ignore(f));
            if sample.is_empty() {
                return None;
            }
            let (ma, mb) = (&lib.mods[a], &lib.mods[b]);
            if !only.is_empty() && !only.contains(&ma.id) && !only.contains(&mb.id) {
                return None;
            }
            sample.sort();
            Some(ConflictHit { a_id: ma.id.clone(), a_name: ma.name.clone(), b_id: mb.id.clone(), b_name: mb.name.clone(), both_enabled: ma.enabled && mb.enabled, count, sample })
        })
        .collect();
    out.sort_by(|x, y| y.both_enabled.cmp(&x.both_enabled).then(y.count.cmp(&x.count)).then(x.a_name.cmp(&y.a_name)));
    out.truncate(limit);
    out
}

