/// A file-looking word: « engine.ogg », « Mods/aircraft », « textures\\a.dds ».
fn file_terms(q: &str) -> Vec<String> {
    q.split_whitespace()
        .map(|w| w.trim_matches(|c: char| "«»\"'?!,;:()[]".contains(c)))
        .filter(|w| {
            let has_ext = w.rsplit_once('.').map(|(a, e)| !a.is_empty() && (2..=5).contains(&e.len()) && e.chars().all(|c| c.is_ascii_alphanumeric())).unwrap_or(false);
            has_ext || w.contains('/') || w.contains('\\')
        })
        .map(|w| w.replace('\\', "/").to_lowercase())
        .collect()
}

/// The keyword rules: a prior per intent (0..1) and whether it is decisive on its own.
pub fn intent_rules(q: &str) -> (Vec<(String, f64)>, bool) {
    let f = format!(" {} ", L::fold(q));
    let has = |ws: &[&str]| ws.iter().any(|w| f.contains(w));
    let files = !file_terms(q).is_empty();
    let conflict = has(&["conflit", "conflict", "overlap", "ecrase", "overwrit", "chevauch", "se battent", "fight over", "clash"]);
    let which_mod = has(&["quel mod", "quels mod", "which mod", "what mod", "qui modifie", "modifie ", "modifies", "replace", "remplace", "provid", "fournit", "touch"]);
    let setting = has(&["reglage", "parametre", "setting", "option", "activer", "desactiver", "turn on", "turn off", "enable ", "disable ", "configur", "changer "]);
    let command = has(&[" ouvr", " open ", " lance", " run ", " export", " import", " scan", " verifi", " verify", " go to", " aller "]);
    let docs = has(&["c'est quoi", "c est quoi", "what is", "what's", "what are", "how ", "comment", "pourquoi", "why", "explain", "explique", "difference", "a quoi sert", "à quoi sert"]);
    let mods = has(&[" mes mods", " my mods", " installed", " installe", " profil", " profile"]);
    let mut p = vec![("docs".to_string(), 0.3), ("setting".to_string(), 0.1), ("files".to_string(), 0.05), ("conflicts".to_string(), 0.05), ("mods".to_string(), 0.1), ("command".to_string(), 0.1)];
    let mut bump = |k: &str, v: f64| {
        if let Some(x) = p.iter_mut().find(|(n, _)| n == k) {
            x.1 += v;
        }
    };
    if conflict {
        bump("conflicts", 0.8);
    }
    if files {
        bump("files", if which_mod { 0.9 } else { 0.6 });
    } else if which_mod && has(&["fichier", " file"]) {
        bump("files", 0.6);
    }
    if setting {
        bump("setting", 0.4);
    }
    if command {
        bump("command", 0.4);
    }
    if docs {
        bump("docs", 0.4);
    }
    if mods {
        bump("mods", 0.3);
    }
    let total: f64 = p.iter().map(|x| x.1).sum();
    for x in p.iter_mut() {
        x.1 /= total;
    }
    p.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
    let decisive = conflict || files;
    (p, decisive)
}

