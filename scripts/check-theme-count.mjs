#!/usr/bin/env node
// check-theme-count — the number of built-in themes the docs promise must be the number shipped.
//
// A count in prose is the most quietly wrong thing a document can contain. `09-bmm-glass` was
// dropped in adee14e9 and both language versions of the themes page kept saying **twelve**
// for every release after it — a claim nothing compiled, nothing ran, and nobody could
// disprove without counting a folder by hand.
//
// This is the same shape as check-diagrams, which pins the diagram count for the same reason.
// The app reads `frontend/assets/builtin-themes/*.json` at boot (themes.rs resolves that
// folder as a bundled resource), so the file count IS the number a user sees.
//
// Usage: node scripts/check-theme-count.mjs
// Exit code 1 when a page's number disagrees with the folder.

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'frontend/assets/builtin-themes';
if (!existsSync(DIR)) {
    console.error(`✗ ${DIR} is missing — refusing to report success`);
    process.exit(2);
}
const count = readdirSync(DIR).filter((f) => f.endsWith('.json')).length;
if (!count) {
    console.error(`✗ no themes found in ${DIR} — refusing to report success`);
    process.exit(2);
}

// Written out, because that is how the pages say it. A page saying "11" would be just as
// true, so the digit is accepted too rather than forcing a rewrite on whoever gets there
// next.
const WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine',
    'ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen',
    'eighteen', 'nineteen', 'twenty'];
const MOTS = ['zéro', 'un', 'deux', 'trois', 'quatre', 'cinq', 'six', 'sept', 'huit', 'neuf',
    'dix', 'onze', 'douze', 'treize', 'quatorze', 'quinze', 'seize', 'dix-sept', 'dix-huit',
    'dix-neuf', 'vingt'];

// Both surfaces: the site's source and the copy bundled into Help & other. The bundled one is
// generated from the site, but it is generated by a script somebody has to remember to run,
// so checking only the source would let the app ship the stale number.
const PAGES = [
    { path: 'BMM Docs/docs/features/themes.md', words: WORDS, re: /\*\*([a-z-]+|\d+)\*\* built-in themes/ },
    { path: 'BMM Docs/docs/features/themes.fr.md', words: MOTS, re: /\*\*([a-zé-]+|\d+)\*\* thèmes intégrés/ },
    { path: 'frontend/assets/docs/en/features/themes.md', words: WORDS, re: /\*\*([a-z-]+|\d+)\*\* built-in themes/ },
    { path: 'frontend/assets/docs/fr/features/themes.md', words: MOTS, re: /\*\*([a-zé-]+|\d+)\*\* thèmes intégrés/ },
];

const fail = [];
let checkedPages = 0;
for (const page of PAGES) {
    if (!existsSync(page.path)) {
        console.log(`  skip  ${page.path} — not present`);
        continue;
    }
    const text = readFileSync(page.path, 'utf8');
    const m = text.match(page.re);
    // A page that stopped stating a number is not a failure — it is a page that can no longer
    // be wrong. Reported so the check does not silently cover nothing.
    if (!m) {
        console.log(`  note  ${page.path} states no count`);
        continue;
    }
    checkedPages += 1;
    const said = /^\d+$/.test(m[1]) ? Number(m[1]) : page.words.indexOf(m[1]);
    if (said !== count) {
        fail.push(`${page.path}: says "${m[1]}" — ${DIR} holds ${count}`);
    }
}

if (fail.length) {
    console.error(`✗ ${fail.length} page(s) promise the wrong number of built-in themes:\n`);
    for (const f of fail) console.error(`  ${f}`);
    console.error('\n  A count in prose is the one claim nothing else can check.');
    process.exit(1);
}
console.log(`✓ ${count} built-in themes, and ${checkedPages} page(s) say so`);
